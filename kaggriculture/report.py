"""
Generate `results.md`: the final measured scoreboard plus the tuned parameter set.

Runs every built-in opponent on both seats, then self-play — self-play is the one that
matters for the leaderboard, because it is the only configuration where somebody else is
also selling melons into the shared market.

    python report.py --episodes 12
"""

import argparse
import json
import statistics
from datetime import datetime, timezone

import harness
from rules import Params, params_dict


def _row(label: str, out: dict, opp_mean: float | None = None) -> str:
    win = f"{out['wins']:.0%}" if "wins" in out else "—"
    opp = f"{opp_mean:,.0f}" if opp_mean is not None else "—"
    return (f"| {label} | {out['episodes']} | **{out['mean']:,.0f}** | {out['stdev']:,.0f} "
            f"| {out['min']:,.0f} | {out['max']:,.0f} | {opp} | {win} |")


def evaluate_pair(params: Params, episodes: int, seed: int, opponent, both_seats=True):
    """Our score and the opponent's, from the same episodes, so win rate is exact."""
    from kaggle_environments import make

    me_scores, opp_scores = [], []
    seats = (0, 1) if both_seats else (0,)
    opp_agent = harness.make_agent(opponent) if isinstance(opponent, Params) else opponent
    for i in range(episodes):
        for seat in seats:
            env = make("kaggriculture", configuration={"episodeSteps": 720, "seed": seed + i})
            players = [harness.make_agent(params), opp_agent]
            if seat == 1:
                players.reverse()
            env.run(players)
            final = env.steps[-1]
            me_scores.append(float(final[seat].reward or 0.0))
            opp_scores.append(float(final[1 - seat].reward or 0.0))
    stdev = statistics.stdev(me_scores) if len(me_scores) > 1 else 0.0
    return {
        "episodes": len(me_scores),
        "mean": statistics.fmean(me_scores),
        "stdev": stdev,
        "min": min(me_scores),
        "max": max(me_scores),
        "wins": sum(m > o for m, o in zip(me_scores, opp_scores)) / len(me_scores),
    }, statistics.fmean(opp_scores)


def main(episodes: int, seed: int) -> None:
    params = harness.Params(**{k: v for k, v in _load().items()
                               if k in Params.__dataclass_fields__})
    lines = [
        "# Results", "",
        f"Generated by `report.py` on {datetime.now(timezone.utc):%Y-%m-%d}, "
        f"{episodes} seeds x both seats per opponent, `episodeSteps=720`.", "",
        "Score is final cash. Both seats are played because atomic market orders "
        "(`HIRE`, `BUY_LAND`) resolve in player order, which hands seat 0 a small "
        "structural edge.", "",
        "| Opponent | Episodes | Our mean | Stdev | Min | Max | Their mean | Win rate |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]

    for label, opponent in (("`pass`", "pass"), ("`starter`", "starter"),
                            ("`random`", "random"), ("**self-play**", params)):
        out, opp_mean = evaluate_pair(params, episodes, seed, opponent)
        lines.append(_row(label, out, opp_mean))
        print(lines[-1])

    lines += ["", "## Tuned parameters", "",
              "Searched by `tune.py` (coordinate descent, paired seeds, "
              "1.5-sigma acceptance gate). Shipped in `params.json`.", "",
              "```json", json.dumps(params_dict(params), indent=2, sort_keys=True), "```"]

    with open("results.md", "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\nwrote results.md")


def _load() -> dict:
    try:
        with open("params.json") as fh:
            return json.load(fh)
    except Exception:
        return params_dict(Params())


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--episodes", type=int, default=12)
    ap.add_argument("--seed", type=int, default=100)
    args = ap.parse_args()
    main(args.episodes, args.seed)
